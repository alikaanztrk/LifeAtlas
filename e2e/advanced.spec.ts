import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const nav = (page: Page, name: string) => page.getByRole('link', { name, exact: true }).click()
const demo = async (page: Page) => {
  await page.goto('./')
  await page.getByRole('button', { name: 'Open the demo' }).click()
  await expect(page.getByRole('heading', { name: 'Archive overview' })).toBeVisible()
}
const places = (page: Page) => nav(page, 'Places')
const trips = (page: Page) => nav(page, 'Trips')
const panel = (page: Page) => page.locator('.trip-detail')

async function saveNamedTrip(page: Page, name: string, first: string, last: string) {
  await page.getByRole('button', { name: 'Create trip', exact: true }).click()
  await panel(page).getByLabel('Trip name').fill(name)
  await panel(page).getByLabel('Start date').fill(first)
  await panel(page).getByLabel('End date').fill(last)
  await panel(page).getByRole('button', { name: 'Create trip', exact: true }).click()
  await expect(panel(page).getByRole('heading', { name })).toBeVisible()
}

