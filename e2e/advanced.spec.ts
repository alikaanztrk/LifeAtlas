test('creates, splits, merges and deletes a manual trip with undo', async ({ page }) => {
  await demo(page)
  await trips(page)
  await saveNamedTrip(page, 'Synthetic weekend', '2025-05-03', '2025-05-04')
  await expect(panel(page).getByText('2 of 2 days')).toBeVisible()
  await panel(page).locator('summary').filter({ hasText: 'Split trip' }).click()
  await panel(page).getByLabel('First date of the second trip').fill('2025-05-04')
  await panel(page).getByLabel('Second trip name').fill('Synthetic Sunday')
  await panel(page).getByRole('button', { name: 'Split trip', exact: true }).click()
  await expect(page.getByRole('button', { name: /Synthetic Sunday/ })).toBeVisible()
  await expect(panel(page).getByText('1 of 1 day')).toBeVisible()
  await panel(page).locator('summary').filter({ hasText: 'Merge trips' }).click()
  await panel(page).getByLabel('Trip to merge with').selectOption({ index: 1 })
  await panel(page).getByRole('button', { name: 'Merge trips', exact: true }).click()
  await expect(page.getByRole('button', { name: /Synthetic Sunday/ })).toHaveCount(0)
  await expect(panel(page).getByText('2 of 2 days')).toBeVisible()
  await panel(page).getByRole('button', { name: 'Delete trip', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete trip', exact: true }).click()
  await expect(page.getByText('There are no saved trips in the selected date range.')).toBeVisible()
  await page.getByRole('button', { name: 'Undo last edit' }).click()
  await expect(page.getByRole('button', { name: /Synthetic weekend/ })).toBeVisible()
})

test('offers an observed overnight suggestion only after Home is marked and saves by explicit choice', async ({ page }) => {
  const rows = [
    { startTime: '2025-05-03T09:00:00Z', endTime: '2025-05-03T12:00:00Z',
      visit: { topCandidate: { name: 'Synthetic anchor', placeId: 'test-home', placeLocation: { lat: -44, lon: -141 } } } },
    { startTime: '2025-05-05T21:00:00Z', endTime: '2025-05-06T03:00:00Z',
      visit: { topCandidate: { name: 'Synthetic away spot', placeId: 'test-away', placeLocation: { lat: -39, lon: -141 } } } },
  ]
  await page.goto('./')
  await page.locator('input[type=file]').setInputFiles({ name: 'synthetic-overnight.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(rows)) })
  await page.getByRole('button', { name: 'Open archive', exact: true }).click()
  await trips(page)
  await expect(page.getByText(/Mark one place as Home/)).toBeVisible()
  await places(page)
  await page.getByRole('button', { name: 'Synthetic anchor', exact: true }).click()
  await page.getByLabel('Category', { exact: true }).selectOption('home')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByText('Changes saved.', { exact: true })).toBeVisible()
  await trips(page)
  await expect(page.getByText(/6 hr observed in one visit/)).toBeVisible()
  await expect(page.getByText('There are no saved trips in the selected date range.')).toBeVisible()
  await page.getByRole('button', { name: 'Review suggestion' }).click()
  await expect(panel(page).getByLabel('Start date')).toHaveValue('2025-05-05')
  await expect(panel(page).getByLabel('End date')).toHaveValue('2025-05-06')
  await panel(page).getByLabel('Trip name').fill('Synthetic overnight')
  await panel(page).getByRole('button', { name: 'Create trip', exact: true }).click()
  await expect(panel(page).getByRole('heading', { name: 'Synthetic overnight' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Review suggestion' })).toHaveCount(0)
})

test('shares the active period with analytics, preserves missing percentages and stays local', async ({ page, context }) => {
  const unexpected: string[] = []
  const errors: string[] = []
  page.on('pageerror', ({ name }) => errors.push(name))
  page.on('console', (message) => { if (message.type() === 'error') errors.push('console') })
  await context.route('**/*', async (route) => {
    const url = new URL(route.request().url())
    if (url.origin !== 'http://127.0.0.1:4180' || url.search || route.request().method() !== 'GET') {
      unexpected.push('request'); await route.abort()
    } else await route.continue()
  })
  await demo(page)
  await nav(page, 'Analytics')
  await expect(page.getByRole('heading', { name: 'Transport by time and distance' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Date range' }).selectOption('custom')
  await page.getByLabel('Start date', { exact: true }).fill('2025-05-03')
  await page.getByLabel('End date', { exact: true }).fill('2025-05-03')
  await page.getByRole('form', { name: 'Date range' }).getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page.locator('.compare-periods')).toContainText('May 3, 2025')
  await expect(page.locator('.compare-periods')).toContainText('May 2, 2025')
  await expect(page.locator('.compare-table').getByRole('row', { name: /Known distance/ })).toContainText('1.71 km')
  await expect(page.getByText('Changes are unavailable when the baseline is missing or zero.')).toBeVisible()
  await page.getByLabel('Comparison start date').fill('2025-05-04')
  await page.getByLabel('Comparison end date').fill('2025-05-05')
  await page.locator('.compare-form').getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page.getByText('The periods contain different numbers of calendar days.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Known movement by weekday' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const transport = page.getByRole('region', { name: 'Transport by time and distance' })
  await transport.focus()
  await expect(transport).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect.poll(() => transport.evaluate((element) => element.scrollLeft)).toBeGreaterThan(0)
  expect(new URL(page.url()).hash).toBe('#/analytics')
  await page.getByRole('heading', { name: 'Most visited places', exact: true }).locator('..')
    .getByRole('button', { name: 'Paper Bay', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Paper Bay' })).toBeVisible()
  await expect(page.locator('.active-scope')).toContainText('May 3, 2025')
  expect(unexpected).toEqual([])
  expect(errors).toEqual([])
})

test('restores persistent edits on reload and merge, and clears them on confirmed replacement', async ({ page }) => {
  test.setTimeout(55_000)
  const importFile = async (name: string) => {
    await nav(page, 'Import')
    await page.locator('input[type=file]').setInputFiles('src/fixtures/synthetic-' + name + '.json')
    await page.getByRole('radio', { name: /In this browser/ }).check()
  }
  await page.goto('./')
  await importFile('android')
  await page.getByRole('button', { name: 'Open archive', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Archive overview' })).toBeVisible()
  await places(page)
  await page.getByRole('button', { name: 'Paper Harbor', exact: true }).click()
  await page.getByLabel('Place name').fill('Persistent synthetic place')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.getByRole('heading', { name: 'Persistent synthetic place' })).toBeVisible()
  await trips(page)
  await saveNamedTrip(page, 'Persistent synthetic trip', '2025-02-02', '2025-02-02')
  await page.reload()
  await expect(page.getByRole('button', { name: /Persistent synthetic trip/ })).toBeVisible()
  await importFile('android')
  await page.getByRole('button', { name: 'Merge archives' }).click()
  await expect(page.getByRole('heading', { name: 'Archive overview' })).toBeVisible()
  await places(page)
  await expect(page.getByRole('button', { name: 'Persistent synthetic place', exact: true })).toBeVisible()
  await importFile('legacy-raw')
  await page.getByRole('button', { name: 'Replace archive', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Replace archive', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Archive overview' })).toBeVisible()
  await trips(page)
  await expect(page.getByText('There are no saved trips in the selected date range.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Undo last edit' })).toBeDisabled()
})
